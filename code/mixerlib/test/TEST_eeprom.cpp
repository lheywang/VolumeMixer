#include "gtest/gtest.h"
#include "eeprom/eeprom.h"

extern struct EEPROM_Header header;
extern struct EEPROM_hash hashs;

/**
 * ===============================================================
 * FIRST : CORRECT PARSER AND BUILDERS
 * ===============================================================
 */

TEST(EEPROM, CorrectParser)
{
	uint8_t buf[128] = {0xbe, 0xef,
						'A', 'A', 'A', 'A', 'A', 'A', 'A', 'A',
						0x0F, 0xFF,
						0x00, 0xFF,
						0x00, 0x0F,
						0x00, 0x00,
						0x0F, 0x00,
						0x0F, 0xAA,
						64,
						0xA0,
						0xC0,
						0xE0,
						0,
						96,
						0xFF, 0xFF, 0xFF, 0xFF,
						0xde, 0xad,
						0xde, 0xad,
						0xde, 0xad,
						0xde, 0xad,
						0xde, 0xad,
						0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
						0x42, 0x13, 0x5b, 0xb2,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0xde, 0xad, 0xbe, 0xef,
						0x4a, 0x14, 0x1c, 0x65};

	// Parse buffer
	int retval = parse_raw_eeprom_header(buf);

	// Comparisons
	ASSERT_EQ(retval, 0);

	// Preambule
	ASSERT_EQ(header.preambule, 0xbeef);

	// SN
	for (int k = 0; k < 8; k++)
	{
		ASSERT_EQ(header.SN[k], 'A');
	}

	// Offset
	EXPECT_NEAR(header.offset, 3.3f, 0.001);
	float res1[] = {0.205f, 0.012f, 0.00f, 3.094f, 3.231};
	for (int k = 0; k < 5; k++)
	{
		EXPECT_NEAR(header.chan_offsets[k], res1[k], 0.001);
	}

	EXPECT_NEAR(header.gain, 1.0f, 0.001);
	float res2[] = {-1.5f, -1.0f, -0.5f, 0.0f, 1.5f};
	for (int k = 0; k < 5; k++)
	{
		EXPECT_NEAR(header.chan_gain[k], res2[k], 0.001);
	}

	for (int k = 0; k < 5; k++)
	{
		ASSERT_EQ(header.default_apps[k], 0xdead);
	}

	for (int k = 0; k < 15; k++)
	{
		ASSERT_EQ(hashs.Icons[k].hash, 0xdead);
		ASSERT_EQ(hashs.Icons[k].address, 0xbeef);
	}
}

